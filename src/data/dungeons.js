// data/dungeons.js — builder A. The 75 named dungeon types (15 per biome). Pure data, no imports.
//
// Entry: { id, biome, name, enter, layout, dir, floors:[min,max], wall, floor, twist, boss:{name,title},
//          loot:{gold:[a,b], gearBonus}, weight }
//   layout  'up'    rooms and corridors, floors shrink as you climb (the classic pyramid generator)
//           'down'  rooms and corridors, floors grow as you descend
//           'maze'  a braided maze            'hall'  a pillared great hall with side chambers
//           'caves' cellular-automaton caverns
//   dir     'up' | 'down'  which way the next floor lies (only decides the stair art and the log lines)
//   wall    solid terrain key for walls; floor: ground terrain key for floors (see data/terrain.js)
//   twist   null or a key of TWISTS (implemented in world/dungeon.js)
//   enter   logged on entry; '{n}' is replaced with the number of floors
//   weight  relative odds of this type at a site of its biome (default 1)

